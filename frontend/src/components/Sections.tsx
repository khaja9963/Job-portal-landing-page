const stepTags = ["AI-drafted", "3 search modes", "20 min", "Scored", "7 stages"];

export function HowItWorks() {
  const ref = useRef<HTMLDivElement>(null);
  const reduce = useReducedMotion();
  const [i, setI] = useState(0);
  const { scrollYProgress } = useScroll({ target: ref, offset: ["start start", "end end"] });
  // only touch state when the derived index actually changes
  useMotionValueEvent(scrollYProgress, "change", (p) => {
    const n = Math.min(steps.length - 1, Math.floor(p * steps.length));
    setI((c) => (c === n ? c : n));
  });
  const scale = useTransform(scrollYProgress, [0, 1], [1.08, 1]);
  const V = steps[i].v;
  return (
    <section id="how" ref={ref} style={{ fontFamily: "var(--font-geist)", height: reduce ? "auto" : `${steps.length * 80}svh` }} className="relative bg-[#ffe9da] text-ink">
      <div className={`${reduce ? "" : "sticky top-0 overflow-hidden"} grid min-h-svh lg:grid-cols-[1.1fr_1fr]`}>
        <div className="flex items-center py-16 pl-6 pr-6 md:pl-10 lg:pl-[max(2.5rem,calc((100vw-72rem)/2))] lg:pr-12">
          <div className="w-full">
          <div>
              <span className="text-[11px] font-semibold uppercase tracking-[0.16em] text-accent">How it works</span>
              <h2 className="font-serif-d mt-4 text-5xl leading-[1.05] md:text-7xl">
                <Words>From job post to <span className="italic">signed offer.</span></Words>
              </h2>
              <ol className="mt-10">
                {steps.map((s, k) => {
                  const lit = reduce || k <= i;
                  return (
                    <li key={s.t} className="border-t border-black/20 transition-opacity duration-500" style={{ opacity: lit ? 1 : 0.28 }}>
                      <button onClick={() => setI(k)} className="flex w-full cursor-pointer items-center gap-4 py-4 text-left focus-visible:outline-2 focus-visible:outline-accent">
                        <span className="w-10 text-2xl font-semibold tracking-tight text-accent">0{k + 1}</span>
                        <span className="flex-1 text-lg font-semibold tracking-tight md:text-2xl">{s.t}</span>
                        <span className="hidden rounded-full border border-black/25 px-3 py-1 text-xs text-ink/70 sm:block">{stepTags[k]}</span>
                      </button>
                      <AnimatePresence initial={false}>
                        {(reduce || k === i) && (
                          <motion.p initial={{ height: 0, opacity: 0 }} animate={{ height: "auto", opacity: 1 }} exit={{ height: 0, opacity: 0 }} className="overflow-hidden pl-14 pr-2 text-sm leading-relaxed text-ink/70">
                            <span className="block pb-4">{s.d}</span>
                          </motion.p>
                        )}
                      </AnimatePresence>
                    </li>
                  );
                })}
                <li className="border-t border-black/20" />
              </ol>
            </div>
          </div>
        </div>

        {/* the screen: flush against the right edge, no card around it */}
        <div className="relative flex items-center justify-center px-6 py-20 lg:px-12">
          <motion.div style={{ scale: reduce ? 1 : scale }} className="w-full max-w-md origin-center">
            <div className="min-h-[340px]">
              <AnimatePresence mode="wait">
                <motion.div key={i} initial={{ opacity: 0, y: 20 }} animate={{ opacity: 1, y: 0 }} exit={{ opacity: 0, y: -12 }} transition={{ duration: 0.4, ease: [0.16, 1, 0.3, 1] }}>
                  <V />
                </motion.div>
              </AnimatePresence>
            </div>
          </motion.div>
          <div className="absolute inset-x-6 bottom-8 flex items-center justify-between text-[11px] font-semibold uppercase tracking-[0.14em] lg:inset-x-12">
            <span className="text-accent">Step {i + 1} / {steps.length}</span>
            <span className="text-ink/55">{stepTags[i]}</span>
          </div>
        </div>
      </div>
    </section>
  );
}

